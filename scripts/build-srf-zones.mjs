#!/usr/bin/env node
// offshore-surf step 3: src/data/srfZones.ts, the NWS SRF office and zone of each spot, from docs/forecast/data/surf-height-sources.json (which maps a spot to the zone that contains it; see docs/forecast/SURF-HEIGHT-SOURCES.md).
//   node scripts/build-srf-zones.mjs > src/data/srfZones.ts      (a test fails if the committed file differs from this output)
import fs from 'node:fs';
const j = JSON.parse(fs.readFileSync(new URL('../docs/forecast/data/surf-height-sources.json', import.meta.url), 'utf8'));
const rows = Object.entries(j.spots).filter(([, s]) => s.nws_srf?.office && s.nws_srf?.zone).map(([id, s]) => [id, s.nws_srf.office, s.nws_srf.zone]).sort((a, b) => a[0].localeCompare(b[0]));
console.log(`// GENERATED by scripts/build-srf-zones.mjs from docs/forecast/data/surf-height-sources.json (NWS zone polygons containing each spot). Do not edit.
// spot id -> "<SRF office>|<UGC zone>". The NWS Surf Zone Forecast for that zone is served at /api/srf?office=<office> (services/srf-serve.mjs).
export const SRF_ZONE_OF: Readonly<Record<string, string>> = {
${rows.map(([id, o, z]) => ` ${JSON.stringify(id)}: '${o}|${z}',`).join('\n')}
};`);
