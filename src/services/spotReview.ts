import {PROFILE_FIELDS, FIELD_LABEL, type SpotProfile, type Source, type Sourced} from '../ocean/spotProfile.ts';
import {spotProfiles} from '../ocean/spotProfiles.ts';
import {evidenceSpots} from '../ocean/spots.ts';
import {mopCandidates, mopPoint, distanceKm} from '../ocean/mop.ts';
import {nearestTideStations, tideStations} from '../ocean/tideStations.ts';

const fmt = (v: unknown) => (v === null || v === undefined ? '—' : typeof v === 'string' ? v : JSON.stringify(v).replace(/"/g, ''));
const cell = (s: string) => s.replace(/\|/g, '/').replace(/\n/g, ' ');
const cite = (s: Source) => `[${cell(s.title)}](${s.url}) (retrieved ${s.retrievedOn})${s.quote ? `: “${cell(s.quote)}”` : ''}`;
const evidence = (x: Sourced<unknown>) => {
  const src = x.value !== null ? x.sources : x.proposal?.sources ?? [];
  return src.length ? src.map(cite).join('<br>') : 'none found';
};

/** The owner's review sheet, generated from the registry so it can never drift from it (a test compares it with the committed file). */
export function renderSpotReview(profiles: SpotProfile[] = spotProfiles): string {
  const L: string[] = [];
  L.push('# Spot facts: your review list', '');
  L.push('Generated by `node --experimental-strip-types docs/forecast/data/build-spot-review.ts` from `src/ocean/spotProfiles.ts`. **Do not edit by hand.**', '');
  L.push('**How to use it.** For every row, tick one box. Nothing here is used by the app until you approve it: the registry keeps every row with “Recorded now: —” as unknown, and the rating is unchanged. One exception to know about: the experimental breaking-size estimate already uses two engineering assumptions for Ocean Beach (swell window and 8 s minimum, from T-008); approving or replacing them here ends that. Approving a row records you and the date as the reviewer.', '');
  L.push('Sources must be an agency page, a peer-reviewed or agency report, or your own local knowledge. Commercial surf-report text and forum posts are not sources, and none are used here. Where the sources checked had nothing on a fact, the row says “none found”: that fact needs your local knowledge, or stays unknown.', '');
  for (const p of profiles) {
    const sp = evidenceSpots.find((e) => e.id === p.spotId)!;
    L.push(`## ${sp.name} (${p.spotId})`, '', '| Fact | Recorded now | Proposed (waiting for you) | Evidence | Your decision |', '|---|---|---|---|---|');
    for (const f of PROFILE_FIELDS) {
      const x = p[f] as Sourced<unknown>;
      const now = x.value === null ? '—' : `${fmt(x.value)} (${x.status})`;
      const prop = x.proposal ? fmt(x.proposal.value) : '—';
      const ev = x.value !== null || x.proposal ? evidence(x) + (x.proposal?.note ? `<br>*${cell(x.proposal.note)}*` : x.note ? `<br>*${cell(x.note)}*` : '') : x.note ? `none found<br>*${cell(x.note)}*` : 'none found';
      const decision = x.value !== null ? 'Already sourced: ☐ confirm ☐ change to: ____' : x.proposal ? '☐ approve ☐ change to: ____ ☐ unknown' : 'Your local knowledge: ____ ☐ unknown';
      L.push(`| ${FIELD_LABEL[f]} | ${cell(now)} | ${cell(prop)} | ${cell(ev)} | ${decision} |`);
    }
    L.push('');
  }
  L.push('## Nearshore model points (MOP) waiting for assignment', '', 'Measured from each CDIP point’s own file (`scripts/mop-lookup.mjs`). Only Ocean Beach SF023 is assigned today.', '', '| Spot | Point | Position | Depth | Shore normal | Distance from the spot’s query point | Your decision |', '|---|---|---|---|---|---|---|');
  for (const c of mopCandidates) {
    const sp = evidenceSpots.find((e) => e.id === c.spotId)!;
    for (const id of c.mopIds) { const m = mopPoint(id)!; L.push(`| ${sp.name} | ${id} | ${m.lat}, ${m.lon} | ${m.depthM} m | ${m.shoreNormalDeg}° | ${distanceKm(sp.latitude, sp.longitude, m.lat, m.lon).toFixed(1)} km | ☐ assign ☐ not this one |`); }
    L.push(`| ${sp.name} | | | | | | *${cell(c.note)}* |`);
  }
  L.push('', '## Tide stations waiting for assignment', '', `Stations registered: ${tideStations.map((s) => `${s.name} (${s.id})`).join(', ')}. Today the San Francisco station serves only spots near San Francisco; others get no tide. Distances are straight-line and say nothing about whether a station’s tide matches the break.`, '', '| Spot | Nearest stations | Your decision |', '|---|---|---|');
  for (const p of profiles) { const sp = evidenceSpots.find((e) => e.id === p.spotId)!; L.push(`| ${sp.name} | ${nearestTideStations(sp.latitude, sp.longitude).map((n) => `${n.station.name} ${n.distanceKm} km`).join('; ')} | ☐ use ____ ☐ none |`); }
  L.push('');
  return L.join('\n');
}
